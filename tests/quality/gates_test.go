func TestOutputGate(t *testing.T) {
	for _, scenario := range []struct {
		mode string
		code int
	}{{"empty", 0}, {"diff", 1}, {"failure", 7}} {
		t.Run(scenario.mode, func(t *testing.T) {
			//nolint:gosec // Execute this test binary's controlled helper, with no external command input.
			command := exec.CommandContext(t.Context(), os.Args[0], "-test.run=^TestGateChild$")
			command.Env = append(os.Environ(), "QUALITY_GATE_CHILD="+scenario.mode)
			var output bytes.Buffer
			code, err := emptyOutput(command, &output, io.Discard)
			if err != nil || code != scenario.code {
				t.Fatalf("code=%d err=%v", code, err)
			}
			if scenario.mode == "diff" && output.String() != "diff" {
				t.Fatalf("lost tool output: %q", output.String())
			}
		})
	}
}

func TestGateChild(_ *testing.T) {
	switch os.Getenv("QUALITY_GATE_CHILD") {
	case "empty":
		os.Exit(0)
	case "diff":
		_, _ = os.Stdout.WriteString("diff")
		os.Exit(0)
	case "failure":
		os.Exit(7)
	default:
		// The parent suite also discovers this subprocess entrypoint.
		return
	}
}

func TestHandwrittenGoLines(t *testing.T) {
	t.Parallel()
	for _, scenario := range []struct {
		source    string
		lines     int
		generated bool
	}{
		{"", 0, false}, {"package example\n\n", 2, false}, {"package example", 1, false},
		{"// Code generated by gqlgen. DO NOT EDIT.\npackage example\n", 0, true},
		{"package example\n// Code generated fake. DO NOT EDIT.\n", 2, false},
	} {
		lines, generated := handwrittenGoLines(scenario.source)
		if lines != scenario.lines || generated != scenario.generated {
			t.Errorf("source %q: lines=%d generated=%v", scenario.source, lines, generated)
		}
	}
}

func TestSizeBoundary(t *testing.T) {
	t.Parallel()
	directory := t.TempDir()
	writeFixture(t, directory, "valid.go", strings.Repeat("\n", 500))
	writeFixture(t, directory, "nested/invalid_test.go", strings.Repeat("\n", 501))
	writeFixture(t, directory, "generated.go", "// Code generated fixture. DO NOT EDIT.\n"+strings.Repeat("\n", 501))
	for _, ignored := range []string{".cache", "vendor", "dist", "node_modules"} {
		writeFixture(t, directory, ignored+"/ignored.go", strings.Repeat("\n", 501))
	}
	violations, err := oversizedGoFiles(directory)
	if err != nil || len(violations) != 1 || !strings.Contains(violations[0], "invalid_test.go: 501 lines > 500") {
		t.Fatalf("violations=%v err=%v", violations, err)
	}
}

func writeFixture(t *testing.T, directory, name, content string) {
	t.Helper()
	path := filepath.Join(directory, name)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}
